% =========================================================================
% params.m
%
% Расчёт параметров математической модели и ПИ-регулятора САР
% концентрации SO2 в отходящих газах печи Ванюкова.
%
% Используется совместно с моделью SO2_loop.slx (создаётся студентом
% в Simulink R2023b и более поздних версий).
%
% Автор: ______________________
% Группа: ______________________
% Дата:  ______________________
% =========================================================================

clear; clc; close all;

%% 1. Исходные данные технологического процесса
% (см. таблицу 1.1 пояснительной записки)

% Расход кислородно-воздушного дутья, нм^3/ч
Q_dutye_min = 25000;
Q_dutye_nom = 30000;
Q_dutye_max = 35000;

% Концентрация SO2 в отходящих газах, % об.
SO2_min = 35;
SO2_nom = 45;
SO2_max = 55;

% Концентрация O2 в отходящих газах, % об.
O2_nom  = 1.5;

%% 2. Параметры передаточных функций звеньев объекта регулирования
% (см. п. 2.4 пояснительной записки)

% 2.1 Регулирующий клапан (электропневматический привод)
Kv = 120;       % коэффициент передачи, нм^3/(ч * % хода)
Tv = 2.0;       % постоянная времени, с
W_v = tf(Kv, [Tv 1]);

% 2.2 Реактор (печь Ванюкова) по каналу "расход дутья - SO2"
Kr = 0.0035;    % коэффициент передачи, % SO2 на нм^3/ч дутья
Tr = 18;        % основная постоянная времени, с
W_r = tf(Kr, [Tr 1]);

% 2.3 Газоанализатор (запаздывание + апериодическое звено I порядка)
Ta = 3.0;       % постоянная времени анализатора, с
W_a = tf(1, [Ta 1]);

% 2.4 Транспортные запаздывания
tau_tr     = 5.1;  % запаздывание по газоходу, с
tau_sample = 2.9;  % запаздывание линии пробоотбора, с
tau_total  = tau_tr + tau_sample;       % суммарное транспортное запаздывание

% 2.5 Полная передаточная функция объекта (с учётом запаздывания)
% W_obj = W_v * W_r * W_a * exp(-tau_total * s)
W_obj_no_delay = W_v * W_r * W_a;
W_obj          = W_obj_no_delay;
W_obj.InputDelay = tau_total;

%% 3. Приведение к канонической форме (одноёмкостная модель + запаздывание)
% W_ob_canon = K_ob / (T_ob*p + 1) * exp(-tau_eq * p)

K_ob   = 0.42;     % эквивалентный коэффициент передачи (см. формулу 2.7)
T_ob   = 18;       % эквивалентная основная постоянная времени, с
tau_eq = 13;       % эквивалентное транспортное запаздывание, с

W_ob_canon = tf(K_ob, [T_ob 1]);
W_ob_canon.InputDelay = tau_eq;

%% 4. Расчёт параметров ПИ-регулятора по методу Циглера-Никольса
% (см. формулы 2.9, 2.10 пояснительной записки)

Kp_zn = 0.9 * T_ob / (K_ob * tau_eq);   % пропорциональный коэффициент
Ti_zn = 3.3 * tau_eq;                   % время изодрома, с
fprintf('Параметры по Циглеру-Никольсу:\n');
fprintf('  Kp = %.3f, Ti = %.1f с\n\n', Kp_zn, Ti_zn);

% Уточнённые значения после численной оптимизации в PID Tuner
Kp = 2.65;
Ti = 38;
fprintf('Параметры после уточнения PID Tuner:\n');
fprintf('  Kp = %.3f, Ti = %.1f с\n\n', Kp, Ti);

% Передаточная функция ПИ-регулятора
% W_p(p) = Kp * (1 + 1/(Ti*p))
W_p = tf([Kp*Ti Kp], [Ti 0]);

%% 5. Анализ устойчивости

% Передаточная функция разомкнутой системы
W_open = W_p * W_obj;

% Запасы устойчивости
[Gm, Pm, Wcg, Wcp] = margin(W_open);
fprintf('Запасы устойчивости:\n');
fprintf('  Gain margin       = %.2f дБ (норма >= 6 дБ)\n', 20*log10(Gm));
fprintf('  Phase margin      = %.1f град (норма >= 30 град)\n', Pm);
fprintf('  Crit. amp. freq.  = %.4f рад/с\n', Wcg);
fprintf('  Crit. phase freq. = %.4f рад/с\n\n', Wcp);

% Замкнутая система
W_closed = feedback(W_open, 1);

%% 6. Моделирование переходного процесса по уставке

t = 0:0.1:300;        % длительность моделирования, с
ref = 5 * (t > 0);    % ступенчатое изменение уставки на +5 %

[y, t_out] = lsim(W_closed, ref, t);

% Качественные показатели регулирования
info = stepinfo(W_closed, 'SettlingTimeThreshold', 0.05);
fprintf('Показатели качества переходного процесса:\n');
fprintf('  Время регулирования (5%%)  : %.1f с\n', info.SettlingTime);
fprintf('  Перерегулирование          : %.1f %%\n', info.Overshoot);
fprintf('  Время нарастания           : %.1f с\n', info.RiseTime);
fprintf('\n');

%% 7. Графики
figure('Name','Переходный процесс САР SO2','NumberTitle','off');
plot(t_out, ref, '--k', 'LineWidth', 1.5); hold on;
plot(t_out, y,    '-b', 'LineWidth', 1.8);
grid on; xlabel('Время, с'); ylabel('\DeltaSO_2, % об.');
legend('Уставка','Реакция системы','Location','SouthEast');
title('Переходный процесс по отработке ступенчатого задания');
saveas(gcf,'transient_SO2.png');

figure('Name','Bode разомкнутой системы','NumberTitle','off');
bode(W_open); grid on;
title('ЛАЧХ и ЛФЧХ разомкнутой системы');
saveas(gcf,'bode_open.png');

figure('Name','Nyquist разомкнутой системы','NumberTitle','off');
nyquist(W_open); grid on;
title('АФЧХ разомкнутой системы');
saveas(gcf,'nyquist_open.png');

%% 8. Сохранение результатов
save('SO2_model_params.mat', ...
     'Kv','Tv','Kr','Tr','Ta','tau_tr','tau_sample','tau_total', ...
     'K_ob','T_ob','tau_eq','Kp','Ti','W_v','W_r','W_a', ...
     'W_obj','W_ob_canon','W_p','W_open','W_closed');

disp('Параметры сохранены в SO2_model_params.mat');
disp('Используйте load(''SO2_model_params.mat'') в SO2_loop.slx');
